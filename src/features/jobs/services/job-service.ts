import { createClient } from '@/lib/supabase/client';
import type { CreateJobInput } from '../types';

const supabase = createClient();

export async function getMyJobs(userId: string) {
  return supabase
    .from('job_requests')
    .select('*, categories(name)')
    .eq('customer_id', userId)
    .order('created_at', { ascending: false });
}

export async function getJobById(jobId: string) {
  return supabase
    .from('job_requests')
    .select('*, categories(name), profiles!customer_id(full_name, avatar_url)')
    .eq('id', jobId)
    .single();
}

export async function createJob(input: CreateJobInput) {
  const { latitude, longitude, ...jobData } = input;
  return supabase.from('job_requests').insert({
    ...jobData,
    location: `SRID=4326;POINT(${longitude} ${latitude})`,
    geohash: '', // Will be auto-generated by trigger
    status: 'open' as const,
  }).select().single();
}

export async function findNearbyJobs(lat: number, lng: number, radiusKm: number = 15) {
  return supabase.rpc('find_nearby_jobs', {
    artisan_lat: lat,
    artisan_lng: lng,
    radius_km: radiusKm,
  });
}
